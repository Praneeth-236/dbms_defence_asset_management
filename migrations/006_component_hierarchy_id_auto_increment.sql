/*
  Enable MySQL-generated IDs for SUBSYSTEM and COMPONENT creation.

  The migration preserves existing IDs and relationships. The inbound foreign
  keys must be removed before changing their referenced primary-key columns.
  Run with application writers quiesced. MySQL DDL is not transactional across
  statements; an SQL exception invokes recovery, but after a client/server
  interruption inspect the schema and restore every missing FK before retrying.
*/
USE defence_asset_system;

DROP PROCEDURE IF EXISTS apply_component_hierarchy_id_migration;
DELIMITER //
CREATE PROCEDURE apply_component_hierarchy_id_migration()
migration_main: BEGIN
  DECLARE v_count BIGINT DEFAULT 0;
  DECLARE v_subsystem_rows BIGINT DEFAULT 0;
  DECLARE v_subsystem_distinct BIGINT DEFAULT 0;
  DECLARE v_subsystem_min BIGINT DEFAULT 0;
  DECLARE v_subsystem_max BIGINT DEFAULT 0;
  DECLARE v_component_rows BIGINT DEFAULT 0;
  DECLARE v_component_distinct BIGINT DEFAULT 0;
  DECLARE v_component_min BIGINT DEFAULT 0;
  DECLARE v_component_max BIGINT DEFAULT 0;
  DECLARE v_subsystem_extra VARCHAR(128) DEFAULT '';
  DECLARE v_component_extra VARCHAR(128) DEFAULT '';
  DECLARE v_ddl_started TINYINT DEFAULT 0;
  DECLARE v_recovery_failed TINYINT DEFAULT 0;

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    IF v_ddl_started = 1 THEN
      BEGIN
        DECLARE CONTINUE HANDLER FOR SQLEXCEPTION SET v_recovery_failed = 1;

        SELECT COUNT(*) INTO v_count
        FROM information_schema.KEY_COLUMN_USAGE k
        JOIN information_schema.REFERENTIAL_CONSTRAINTS r
          ON r.CONSTRAINT_SCHEMA = k.CONSTRAINT_SCHEMA AND r.TABLE_NAME = k.TABLE_NAME AND r.CONSTRAINT_NAME = k.CONSTRAINT_NAME
        WHERE k.CONSTRAINT_SCHEMA = DATABASE() AND UPPER(k.TABLE_NAME) = 'COMPONENT'
          AND UPPER(k.CONSTRAINT_NAME) = 'COMPONENT_IBFK_1' AND UPPER(k.COLUMN_NAME) = 'SUBSYSTEMID'
          AND UPPER(k.REFERENCED_TABLE_NAME) = 'SUBSYSTEM' AND UPPER(k.REFERENCED_COLUMN_NAME) = 'SUBSYSTEMID'
          AND UPPER(r.DELETE_RULE) = 'NO ACTION' AND UPPER(r.UPDATE_RULE) = 'NO ACTION';
        IF v_count = 0 THEN
          ALTER TABLE COMPONENT ADD CONSTRAINT component_ibfk_1 FOREIGN KEY (SubsystemID)
            REFERENCES SUBSYSTEM (SubsystemID) ON DELETE NO ACTION ON UPDATE NO ACTION;
        END IF;

        SELECT COUNT(*) INTO v_count
        FROM information_schema.KEY_COLUMN_USAGE k
        JOIN information_schema.REFERENTIAL_CONSTRAINTS r
          ON r.CONSTRAINT_SCHEMA = k.CONSTRAINT_SCHEMA AND r.TABLE_NAME = k.TABLE_NAME AND r.CONSTRAINT_NAME = k.CONSTRAINT_NAME
        WHERE k.CONSTRAINT_SCHEMA = DATABASE() AND UPPER(k.TABLE_NAME) = 'COMPONENT_DEPENDENCY'
          AND UPPER(k.CONSTRAINT_NAME) = 'COMPONENT_DEPENDENCY_IBFK_1' AND UPPER(k.COLUMN_NAME) = 'COMPONENTID'
          AND UPPER(k.REFERENCED_TABLE_NAME) = 'COMPONENT' AND UPPER(k.REFERENCED_COLUMN_NAME) = 'COMPONENTID'
          AND UPPER(r.DELETE_RULE) = 'NO ACTION' AND UPPER(r.UPDATE_RULE) = 'NO ACTION';
        IF v_count = 0 THEN
          ALTER TABLE COMPONENT_DEPENDENCY ADD CONSTRAINT component_dependency_ibfk_1 FOREIGN KEY (ComponentID)
            REFERENCES COMPONENT (ComponentID) ON DELETE NO ACTION ON UPDATE NO ACTION;
        END IF;

        SELECT COUNT(*) INTO v_count
        FROM information_schema.KEY_COLUMN_USAGE k
        JOIN information_schema.REFERENTIAL_CONSTRAINTS r
          ON r.CONSTRAINT_SCHEMA = k.CONSTRAINT_SCHEMA AND r.TABLE_NAME = k.TABLE_NAME AND r.CONSTRAINT_NAME = k.CONSTRAINT_NAME
        WHERE k.CONSTRAINT_SCHEMA = DATABASE() AND UPPER(k.TABLE_NAME) = 'COMPONENT_DEPENDENCY'
          AND UPPER(k.CONSTRAINT_NAME) = 'COMPONENT_DEPENDENCY_IBFK_2' AND UPPER(k.COLUMN_NAME) = 'DEPENDSONCOMPONENTID'
          AND UPPER(k.REFERENCED_TABLE_NAME) = 'COMPONENT' AND UPPER(k.REFERENCED_COLUMN_NAME) = 'COMPONENTID'
          AND UPPER(r.DELETE_RULE) = 'NO ACTION' AND UPPER(r.UPDATE_RULE) = 'NO ACTION';
        IF v_count = 0 THEN
          ALTER TABLE COMPONENT_DEPENDENCY ADD CONSTRAINT component_dependency_ibfk_2 FOREIGN KEY (DependsOnComponentID)
            REFERENCES COMPONENT (ComponentID) ON DELETE NO ACTION ON UPDATE NO ACTION;
        END IF;

        SELECT COUNT(*) INTO v_count
        FROM information_schema.KEY_COLUMN_USAGE k
        JOIN information_schema.REFERENTIAL_CONSTRAINTS r
          ON r.CONSTRAINT_SCHEMA = k.CONSTRAINT_SCHEMA AND r.TABLE_NAME = k.TABLE_NAME AND r.CONSTRAINT_NAME = k.CONSTRAINT_NAME
        WHERE k.CONSTRAINT_SCHEMA = DATABASE() AND UPPER(k.TABLE_NAME) = 'COMPONENT_SPARE'
          AND UPPER(k.CONSTRAINT_NAME) = 'COMPONENT_SPARE_IBFK_1' AND UPPER(k.COLUMN_NAME) = 'COMPONENTID'
          AND UPPER(k.REFERENCED_TABLE_NAME) = 'COMPONENT' AND UPPER(k.REFERENCED_COLUMN_NAME) = 'COMPONENTID'
          AND UPPER(r.DELETE_RULE) = 'NO ACTION' AND UPPER(r.UPDATE_RULE) = 'NO ACTION';
        IF v_count = 0 THEN
          ALTER TABLE COMPONENT_SPARE ADD CONSTRAINT component_spare_ibfk_1 FOREIGN KEY (ComponentID)
            REFERENCES COMPONENT (ComponentID) ON DELETE NO ACTION ON UPDATE NO ACTION;
        END IF;
      END;
      IF v_recovery_failed = 1 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Migration failed and automatic restoration of one or more hierarchy foreign keys failed; inspect before retrying.';
      END IF;
    END IF;
    RESIGNAL;
  END;

  IF DATABASE() <> 'defence_asset_system' THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Wrong database selected; expected defence_asset_system.';
  END IF;
  IF VERSION() NOT LIKE '8.0.46%' THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Unexpected MySQL version; review this migration before applying.';
  END IF;

  SELECT COUNT(*) INTO v_count FROM information_schema.TABLES
  WHERE TABLE_SCHEMA = DATABASE() AND UPPER(TABLE_NAME) IN ('ASSET','SUBSYSTEM','COMPONENT','COMPONENT_DEPENDENCY','COMPONENT_SPARE','SPARE_PART')
    AND TABLE_TYPE = 'BASE TABLE' AND UPPER(ENGINE) = 'INNODB' AND UPPER(TABLE_COLLATION) = 'UTF8MB4_0900_AI_CI';
  IF v_count <> 6 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Expected hierarchy and related tables/engines/collations differ.'; END IF;

  SELECT COUNT(*) INTO v_count FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND UPPER(TABLE_NAME) = 'SUBSYSTEM';
  IF v_count <> 5 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'SUBSYSTEM column count differs from the reviewed schema.'; END IF;
  SELECT COUNT(*) INTO v_count FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND UPPER(TABLE_NAME) = 'SUBSYSTEM' AND (
    (UPPER(COLUMN_NAME)='SUBSYSTEMID' AND COLUMN_TYPE='int' AND IS_NULLABLE='NO' AND COLUMN_KEY='PRI' AND EXTRA IN ('','auto_increment') AND COLUMN_DEFAULT IS NULL) OR
    (UPPER(COLUMN_NAME)='SUBSYSTEMNAME' AND COLUMN_TYPE='varchar(100)' AND IS_NULLABLE='NO' AND EXTRA='' AND COLUMN_DEFAULT IS NULL) OR
    (UPPER(COLUMN_NAME)='DESCRIPTION' AND COLUMN_TYPE='varchar(255)' AND IS_NULLABLE='YES' AND EXTRA='' AND COLUMN_DEFAULT IS NULL) OR
    (UPPER(COLUMN_NAME)='CRITICALITYLEVEL' AND COLUMN_TYPE='varchar(20)' AND IS_NULLABLE='YES' AND EXTRA='' AND COLUMN_DEFAULT IS NULL) OR
    (UPPER(COLUMN_NAME)='ASSETID' AND COLUMN_TYPE='int' AND IS_NULLABLE='NO' AND EXTRA='' AND COLUMN_DEFAULT IS NULL));
  IF v_count <> 5 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'SUBSYSTEM column definitions differ from the reviewed schema.'; END IF;

  SELECT COUNT(*) INTO v_count FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND UPPER(TABLE_NAME) = 'COMPONENT';
  IF v_count <> 6 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'COMPONENT column count differs from the reviewed schema.'; END IF;
  SELECT COUNT(*) INTO v_count FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND UPPER(TABLE_NAME) = 'COMPONENT' AND (
    (UPPER(COLUMN_NAME)='COMPONENTID' AND COLUMN_TYPE='int' AND IS_NULLABLE='NO' AND COLUMN_KEY='PRI' AND EXTRA IN ('','auto_increment') AND COLUMN_DEFAULT IS NULL) OR
    (UPPER(COLUMN_NAME)='COMPONENTNAME' AND COLUMN_TYPE='varchar(100)' AND IS_NULLABLE='NO' AND EXTRA='' AND COLUMN_DEFAULT IS NULL) OR
    (UPPER(COLUMN_NAME)='DESCRIPTION' AND COLUMN_TYPE='varchar(255)' AND IS_NULLABLE='YES' AND EXTRA='' AND COLUMN_DEFAULT IS NULL) OR
    (UPPER(COLUMN_NAME)='CRITICALITYLEVEL' AND COLUMN_TYPE='varchar(20)' AND IS_NULLABLE='YES' AND EXTRA='' AND COLUMN_DEFAULT IS NULL) OR
    (UPPER(COLUMN_NAME)='ISREPAIRABLE' AND COLUMN_TYPE='varchar(5)' AND IS_NULLABLE='YES' AND EXTRA='' AND COLUMN_DEFAULT IS NULL) OR
    (UPPER(COLUMN_NAME)='SUBSYSTEMID' AND COLUMN_TYPE='int' AND IS_NULLABLE='NO' AND EXTRA='' AND COLUMN_DEFAULT IS NULL));
  IF v_count <> 6 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'COMPONENT column definitions differ from the reviewed schema.'; END IF;

  SELECT EXTRA INTO v_subsystem_extra FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND UPPER(TABLE_NAME)='SUBSYSTEM' AND UPPER(COLUMN_NAME)='SUBSYSTEMID';
  SELECT EXTRA INTO v_component_extra FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND UPPER(TABLE_NAME)='COMPONENT' AND UPPER(COLUMN_NAME)='COMPONENTID';
  IF v_subsystem_extra NOT IN ('','auto_increment') OR v_component_extra NOT IN ('','auto_increment') THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Hierarchy ID columns have unexpected attributes.';
  END IF;

  SELECT COUNT(*) INTO v_count FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=DATABASE() AND UPPER(TABLE_NAME)='SUBSYSTEM' AND UPPER(INDEX_NAME)='PRIMARY';
  IF v_count<>1 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'SUBSYSTEM primary key must be exactly SubsystemID.'; END IF;
  SELECT COUNT(*) INTO v_count FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=DATABASE() AND UPPER(TABLE_NAME)='SUBSYSTEM' AND UPPER(INDEX_NAME)='PRIMARY' AND UPPER(COLUMN_NAME)='SUBSYSTEMID' AND SEQ_IN_INDEX=1;
  IF v_count<>1 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'SUBSYSTEM primary key differs from reviewed schema.'; END IF;
  SELECT COUNT(*) INTO v_count FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=DATABASE() AND UPPER(TABLE_NAME)='COMPONENT' AND UPPER(INDEX_NAME)='PRIMARY';
  IF v_count<>1 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'COMPONENT primary key must be exactly ComponentID.'; END IF;
  SELECT COUNT(*) INTO v_count FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=DATABASE() AND UPPER(TABLE_NAME)='COMPONENT' AND UPPER(INDEX_NAME)='PRIMARY' AND UPPER(COLUMN_NAME)='COMPONENTID' AND SEQ_IN_INDEX=1;
  IF v_count<>1 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'COMPONENT primary key differs from reviewed schema.'; END IF;

  SELECT COUNT(*) INTO v_count FROM information_schema.KEY_COLUMN_USAGE k JOIN information_schema.REFERENTIAL_CONSTRAINTS r
    ON r.CONSTRAINT_SCHEMA=k.CONSTRAINT_SCHEMA AND r.TABLE_NAME=k.TABLE_NAME AND r.CONSTRAINT_NAME=k.CONSTRAINT_NAME
  WHERE k.CONSTRAINT_SCHEMA=DATABASE() AND (
    (UPPER(k.TABLE_NAME)='SUBSYSTEM' AND UPPER(k.CONSTRAINT_NAME)='SUBSYSTEM_IBFK_1' AND UPPER(k.COLUMN_NAME)='ASSETID' AND UPPER(k.REFERENCED_TABLE_NAME)='ASSET' AND UPPER(k.REFERENCED_COLUMN_NAME)='ASSETID') OR
    (UPPER(k.TABLE_NAME)='COMPONENT' AND UPPER(k.CONSTRAINT_NAME)='COMPONENT_IBFK_1' AND UPPER(k.COLUMN_NAME)='SUBSYSTEMID' AND UPPER(k.REFERENCED_TABLE_NAME)='SUBSYSTEM' AND UPPER(k.REFERENCED_COLUMN_NAME)='SUBSYSTEMID') OR
    (UPPER(k.TABLE_NAME)='COMPONENT_DEPENDENCY' AND UPPER(k.CONSTRAINT_NAME)='COMPONENT_DEPENDENCY_IBFK_1' AND UPPER(k.COLUMN_NAME)='COMPONENTID' AND UPPER(k.REFERENCED_TABLE_NAME)='COMPONENT' AND UPPER(k.REFERENCED_COLUMN_NAME)='COMPONENTID') OR
    (UPPER(k.TABLE_NAME)='COMPONENT_DEPENDENCY' AND UPPER(k.CONSTRAINT_NAME)='COMPONENT_DEPENDENCY_IBFK_2' AND UPPER(k.COLUMN_NAME)='DEPENDSONCOMPONENTID' AND UPPER(k.REFERENCED_TABLE_NAME)='COMPONENT' AND UPPER(k.REFERENCED_COLUMN_NAME)='COMPONENTID') OR
    (UPPER(k.TABLE_NAME)='COMPONENT_SPARE' AND UPPER(k.CONSTRAINT_NAME)='COMPONENT_SPARE_IBFK_1' AND UPPER(k.COLUMN_NAME)='COMPONENTID' AND UPPER(k.REFERENCED_TABLE_NAME)='COMPONENT' AND UPPER(k.REFERENCED_COLUMN_NAME)='COMPONENTID') OR
    (UPPER(k.TABLE_NAME)='COMPONENT_SPARE' AND UPPER(k.CONSTRAINT_NAME)='COMPONENT_SPARE_IBFK_2' AND UPPER(k.COLUMN_NAME)='SPAREPARTID' AND UPPER(k.REFERENCED_TABLE_NAME)='SPARE_PART' AND UPPER(k.REFERENCED_COLUMN_NAME)='SPAREPARTID'))
    AND UPPER(r.DELETE_RULE)='NO ACTION' AND UPPER(r.UPDATE_RULE)='NO ACTION';
  IF v_count<>6 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'One or more hierarchy foreign keys or rules differ from the reviewed schema.'; END IF;
  SELECT COUNT(*) INTO v_count FROM information_schema.KEY_COLUMN_USAGE WHERE CONSTRAINT_SCHEMA=DATABASE() AND UPPER(TABLE_NAME) IN ('SUBSYSTEM','COMPONENT','COMPONENT_DEPENDENCY','COMPONENT_SPARE') AND REFERENCED_TABLE_NAME IS NOT NULL;
  IF v_count<>6 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Unexpected or missing hierarchy foreign-key relationships.'; END IF;
  SELECT COUNT(*) INTO v_count FROM information_schema.KEY_COLUMN_USAGE WHERE REFERENCED_TABLE_SCHEMA=DATABASE() AND UPPER(REFERENCED_TABLE_NAME)='SUBSYSTEM' AND UPPER(REFERENCED_COLUMN_NAME)='SUBSYSTEMID';
  IF v_count<>1 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Unexpected inbound references to SUBSYSTEM.SubsystemID.'; END IF;
  SELECT COUNT(*) INTO v_count FROM information_schema.KEY_COLUMN_USAGE WHERE REFERENCED_TABLE_SCHEMA=DATABASE() AND UPPER(REFERENCED_TABLE_NAME)='COMPONENT' AND UPPER(REFERENCED_COLUMN_NAME)='COMPONENTID';
  IF v_count<>3 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Unexpected inbound references to COMPONENT.ComponentID.'; END IF;

  SELECT COUNT(*),COUNT(DISTINCT SubsystemID),COALESCE(MIN(SubsystemID),0),COALESCE(MAX(SubsystemID),0) INTO v_subsystem_rows,v_subsystem_distinct,v_subsystem_min,v_subsystem_max FROM SUBSYSTEM;
  SELECT COUNT(*),COUNT(DISTINCT ComponentID),COALESCE(MIN(ComponentID),0),COALESCE(MAX(ComponentID),0) INTO v_component_rows,v_component_distinct,v_component_min,v_component_max FROM COMPONENT;
  IF v_subsystem_rows<>v_subsystem_distinct OR v_component_rows<>v_component_distinct THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Duplicate hierarchy IDs detected.'; END IF;
  IF (v_subsystem_rows>0 AND v_subsystem_min<=0) OR (v_component_rows>0 AND v_component_min<=0) OR v_subsystem_max>=2147483647 OR v_component_max>=2147483647 THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Hierarchy IDs must be positive signed INT values below the INT limit.';
  END IF;
  SELECT COUNT(*) INTO v_count FROM COMPONENT c LEFT JOIN SUBSYSTEM s ON s.SubsystemID=c.SubsystemID WHERE s.SubsystemID IS NULL;
  IF v_count<>0 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'COMPONENT contains orphan SubsystemID values.'; END IF;
  SELECT COUNT(*) INTO v_count FROM COMPONENT_DEPENDENCY d LEFT JOIN COMPONENT c ON c.ComponentID=d.ComponentID WHERE c.ComponentID IS NULL;
  IF v_count<>0 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'COMPONENT_DEPENDENCY contains orphan ComponentID values.'; END IF;
  SELECT COUNT(*) INTO v_count FROM COMPONENT_DEPENDENCY d LEFT JOIN COMPONENT c ON c.ComponentID=d.DependsOnComponentID WHERE c.ComponentID IS NULL;
  IF v_count<>0 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'COMPONENT_DEPENDENCY contains orphan DependsOnComponentID values.'; END IF;
  SELECT COUNT(*) INTO v_count FROM COMPONENT_SPARE cs LEFT JOIN COMPONENT c ON c.ComponentID=cs.ComponentID WHERE c.ComponentID IS NULL;
  IF v_count<>0 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'COMPONENT_SPARE contains orphan ComponentID values.'; END IF;
  SELECT COUNT(*) INTO v_count FROM COMPONENT_SPARE cs LEFT JOIN SPARE_PART sp ON sp.SparePartID=cs.SparePartID WHERE sp.SparePartID IS NULL;
  IF v_count<>0 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'COMPONENT_SPARE contains orphan SparePartID values.'; END IF;

  IF v_subsystem_extra='auto_increment' AND v_component_extra='auto_increment' THEN
    SELECT 'Already complete: both hierarchy IDs are AUTO_INCREMENT.' AS Result;
    LEAVE migration_main;
  END IF;
  IF v_subsystem_extra='auto_increment' OR v_component_extra='auto_increment' THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Partial AUTO_INCREMENT state detected; stop for manual schema review.';
  END IF;

  SELECT VERSION() AS MySQLVersion,DATABASE() AS TargetDatabase,v_subsystem_rows AS ExistingSubsystemRows,v_subsystem_min AS MinSubsystemID,v_subsystem_max AS MaxSubsystemID,v_component_rows AS ExistingComponentRows,v_component_min AS MinComponentID,v_component_max AS MaxComponentID;
  SET v_ddl_started=1;
  ALTER TABLE COMPONENT DROP FOREIGN KEY component_ibfk_1;
  ALTER TABLE COMPONENT_DEPENDENCY DROP FOREIGN KEY component_dependency_ibfk_1;
  ALTER TABLE COMPONENT_DEPENDENCY DROP FOREIGN KEY component_dependency_ibfk_2;
  ALTER TABLE COMPONENT_SPARE DROP FOREIGN KEY component_spare_ibfk_1;

  ALTER TABLE SUBSYSTEM MODIFY COLUMN SubsystemID INT NOT NULL AUTO_INCREMENT;
  ALTER TABLE COMPONENT MODIFY COLUMN ComponentID INT NOT NULL AUTO_INCREMENT;

  ALTER TABLE COMPONENT ADD CONSTRAINT component_ibfk_1 FOREIGN KEY (SubsystemID) REFERENCES SUBSYSTEM (SubsystemID) ON DELETE NO ACTION ON UPDATE NO ACTION;
  ALTER TABLE COMPONENT_DEPENDENCY ADD CONSTRAINT component_dependency_ibfk_1 FOREIGN KEY (ComponentID) REFERENCES COMPONENT (ComponentID) ON DELETE NO ACTION ON UPDATE NO ACTION;
  ALTER TABLE COMPONENT_DEPENDENCY ADD CONSTRAINT component_dependency_ibfk_2 FOREIGN KEY (DependsOnComponentID) REFERENCES COMPONENT (ComponentID) ON DELETE NO ACTION ON UPDATE NO ACTION;
  ALTER TABLE COMPONENT_SPARE ADD CONSTRAINT component_spare_ibfk_1 FOREIGN KEY (ComponentID) REFERENCES COMPONENT (ComponentID) ON DELETE NO ACTION ON UPDATE NO ACTION;

  SELECT COUNT(*) INTO v_count FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND UPPER(TABLE_NAME)='SUBSYSTEM' AND UPPER(COLUMN_NAME)='SUBSYSTEMID' AND EXTRA='auto_increment';
  IF v_count<>1 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'SubsystemID AUTO_INCREMENT verification failed.'; END IF;
  SELECT COUNT(*) INTO v_count FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND UPPER(TABLE_NAME)='COMPONENT' AND UPPER(COLUMN_NAME)='COMPONENTID' AND EXTRA='auto_increment';
  IF v_count<>1 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ComponentID AUTO_INCREMENT verification failed.'; END IF;
  SELECT COUNT(*) INTO v_count FROM information_schema.KEY_COLUMN_USAGE k JOIN information_schema.REFERENTIAL_CONSTRAINTS r
    ON r.CONSTRAINT_SCHEMA=k.CONSTRAINT_SCHEMA AND r.TABLE_NAME=k.TABLE_NAME AND r.CONSTRAINT_NAME=k.CONSTRAINT_NAME
  WHERE k.CONSTRAINT_SCHEMA=DATABASE() AND UPPER(k.TABLE_NAME) IN ('COMPONENT','COMPONENT_DEPENDENCY','COMPONENT_SPARE')
    AND ((UPPER(k.CONSTRAINT_NAME)='COMPONENT_IBFK_1' AND UPPER(k.COLUMN_NAME)='SUBSYSTEMID' AND UPPER(k.REFERENCED_TABLE_NAME)='SUBSYSTEM' AND UPPER(k.REFERENCED_COLUMN_NAME)='SUBSYSTEMID') OR
         (UPPER(k.CONSTRAINT_NAME)='COMPONENT_DEPENDENCY_IBFK_1' AND UPPER(k.COLUMN_NAME)='COMPONENTID' AND UPPER(k.REFERENCED_TABLE_NAME)='COMPONENT' AND UPPER(k.REFERENCED_COLUMN_NAME)='COMPONENTID') OR
         (UPPER(k.CONSTRAINT_NAME)='COMPONENT_DEPENDENCY_IBFK_2' AND UPPER(k.COLUMN_NAME)='DEPENDSONCOMPONENTID' AND UPPER(k.REFERENCED_TABLE_NAME)='COMPONENT' AND UPPER(k.REFERENCED_COLUMN_NAME)='COMPONENTID') OR
         (UPPER(k.CONSTRAINT_NAME)='COMPONENT_SPARE_IBFK_1' AND UPPER(k.COLUMN_NAME)='COMPONENTID' AND UPPER(k.REFERENCED_TABLE_NAME)='COMPONENT' AND UPPER(k.REFERENCED_COLUMN_NAME)='COMPONENTID'))
    AND UPPER(r.DELETE_RULE)='NO ACTION' AND UPPER(r.UPDATE_RULE)='NO ACTION';
  IF v_count<>4 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Recreated hierarchy foreign keys failed verification.'; END IF;
  SET v_ddl_started=0;
  SELECT 'Hierarchy AUTO_INCREMENT migration applied; IDs and relationships preserved.' AS Result,v_subsystem_rows AS PreservedSubsystemRows,v_subsystem_min AS MinSubsystemID,v_subsystem_max AS MaxSubsystemID,v_component_rows AS PreservedComponentRows,v_component_min AS MinComponentID,v_component_max AS MaxComponentID;
END//
DELIMITER ;

CALL apply_component_hierarchy_id_migration();
DROP PROCEDURE apply_component_hierarchy_id_migration;
